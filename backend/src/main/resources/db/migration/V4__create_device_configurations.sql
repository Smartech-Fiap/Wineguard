CREATE TABLE device_configurations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL
        REFERENCES devices(id) ON DELETE CASCADE,

    protocol_version VARCHAR(10) NOT NULL DEFAULT 'v1',
    revision BIGINT NOT NULL,

    temperature_min NUMERIC(12, 3) NOT NULL,
    temperature_max NUMERIC(12, 3) NOT NULL,
    humidity_min NUMERIC(12, 3) NOT NULL,
    humidity_max NUMERIC(12, 3) NOT NULL,
    luminosity_max INTEGER NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    rejection_reason VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmed_at TIMESTAMPTZ,

    CONSTRAINT uk_device_configuration_revision
        UNIQUE (device_id, revision),

    CONSTRAINT ck_configuration_protocol
        CHECK (protocol_version = 'v1'),

    CONSTRAINT ck_configuration_revision
        CHECK (revision BETWEEN 1 AND 4294967295),

    CONSTRAINT ck_configuration_temperature
        CHECK (
            temperature_min >= -20
            AND temperature_max <= 60
            AND temperature_min < temperature_max
        ),

    CONSTRAINT ck_configuration_humidity
        CHECK (
            humidity_min >= 0
            AND humidity_max <= 100
            AND humidity_min < humidity_max
        ),

    CONSTRAINT ck_configuration_luminosity
        CHECK (luminosity_max BETWEEN 0 AND 4095),

    CONSTRAINT ck_configuration_status
        CHECK (
            status IN ('PENDING', 'APPLIED', 'REJECTED', 'UNCONFIRMED')
        )
);

-- Impede outro envio enquanto o resultado anterior estiver indefinido.
CREATE UNIQUE INDEX uk_device_configuration_unresolved
    ON device_configurations (device_id)
    WHERE status IN ('PENDING', 'UNCONFIRMED');
