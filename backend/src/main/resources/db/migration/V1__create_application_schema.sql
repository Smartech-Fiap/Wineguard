CREATE TABLE environments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(500)
);

CREATE TABLE devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    fiware_id VARCHAR(255) NOT NULL,
    fiware_type VARCHAR(100) NOT NULL,
    fiware_service VARCHAR(100) NOT NULL,
    fiware_service_path VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    environment_id BIGINT NOT NULL REFERENCES environments(id),
    CONSTRAINT uk_devices_fiware UNIQUE (fiware_service, fiware_service_path, fiware_id)
);

CREATE INDEX idx_devices_environment_id ON devices(environment_id);

CREATE TABLE device_limits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    metric VARCHAR(20) NOT NULL CHECK (metric IN ('TEMPERATURE', 'HUMIDITY', 'LUMINOSITY')),
    minimum_value NUMERIC(12, 3),
    maximum_value NUMERIC(12, 3),
    unit VARCHAR(20) NOT NULL,
    CONSTRAINT uk_device_metric UNIQUE (device_id, metric),
    CONSTRAINT ck_device_limit_has_value CHECK (minimum_value IS NOT NULL OR maximum_value IS NOT NULL),
    CONSTRAINT ck_device_limit_order CHECK (minimum_value IS NULL OR maximum_value IS NULL OR minimum_value <= maximum_value)
);
